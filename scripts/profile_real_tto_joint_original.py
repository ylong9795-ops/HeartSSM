"""Measure the actual Original-Motion Joint backward without an optimizer update.

Uses the frozen production optimizer itself. A process-local Adam.step hook
records peak memory and stops BEFORE the first parameter update. No geometry
verdict is mocked, and no real TTO result is generated by this instrumentation.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config',default='configs/real_tto_joint_v1.yaml')
    parser.add_argument('--output',default='outputs/real_tto_joint_v1_20261016/independent_audit/original_motion_memory_preflight.json')
    parser.add_argument('--batch-size',type=int,default=2)
    parser.add_argument('--child',action='store_true')
    parser.add_argument('--fraction',type=float)
    args=parser.parse_args()
    from tto.config import load_config,resolve
    from tto.io import write_json,sha256
    config=load_config(resolve(args.config))
    if not args.child:
        from tto.gpu import select_gpu
        def probe(device):
            with tempfile.TemporaryDirectory(prefix='heartssm-original-motion-probe-') as temporary:
                path=Path(temporary)/'result.json'
                command=[sys.executable,str(Path(__file__).resolve()),'--child','--config',str(resolve(args.config)),
                    '--output',str(path),'--batch-size',str(args.batch_size),'--fraction',
                    str(min(.9,.85*device['free_mib']/device['total_mib']))]
                env=dict(os.environ,CUDA_VISIBLE_DEVICES=device['uuid'])
                result=subprocess.run(command,env=env,capture_output=True,text=True)
                if result.returncode:raise RuntimeError(result.stderr[-3000:]+result.stdout[-500:])
                return json.loads(path.read_text())
        selection=select_gpu('auto',probe,margin_fraction=config['runtime']['gpu_margin_fraction'])
        selection.update(auditor_sha256=sha256(Path(__file__)),scope='Actual Original-Motion full Joint forward/backward; no optimizer update',
            clinical_optimizer_steps_executed=0)
        write_json(resolve(args.output),selection)
        print(json.dumps(dict(selected=selection['selected'],measurement=selection['attempts'][-1]['measurement'])))
        return 0
    import torch
    from unittest.mock import patch
    from tto.dataset import RealTTODataset,collate_patients
    from tto.prior import FrozenNeuralFFDPrior
    from tto.motion import MotionPropagation
    from tto.losses import observation_cells
    from tto.evaluation import RealTTOEvaluator
    from tto.geometry_guard import TTOGeometryGuard
    from tto.shape_pose_joint import JointShapePoseOptimizer
    from tto.io import read_json
    torch.set_num_threads(config['runtime']['threads'])
    torch.cuda.set_per_process_memory_fraction(args.fraction,0)
    torch.backends.cuda.matmul.allow_tf32=False;torch.backends.cudnn.allow_tf32=False
    torch.backends.cudnn.benchmark=False;torch.manual_seed(config['runtime']['seed'])
    torch.cuda.reset_peak_memory_stats();started=time.monotonic()
    prior=FrozenNeuralFFDPrior(resolve(config['prior']['checkpoint']),device='cuda:0',expected_sha256=config['prior']['sha256'])
    data=dict(config['data'],load_images=False)
    patients=[];failures=[]
    for name in config['experiment']['cohort']:
        try:patients.append(RealTTODataset(resolve(data['root']),[name],config=data)[0])
        except Exception as error:failures.append(dict(patient=name,error=repr(error)))
    def workload(patient):
        return sum(patient.views[r['view']]['masks'].shape[-2]*patient.views[r['view']]['masks'].shape[-1]
                   for r in observation_cells([patient],config['supervision']) if r['used'])
    patients.sort(key=workload,reverse=True);patients=patients[:args.batch_size]
    if not patients:raise ValueError('No valid native patient for actual Original-Motion workload measurement')
    initial=prior.initialize(collate_patients(patients)['observations'])
    calibration=read_json(resolve(config['prior']['calibration']))
    poses=[{key:torch.tensor(calibration['initial_pose'][key],device=prior.device,dtype=torch.float32)
            for key in ('R','center_mm')} for patient in patients]
    guard=TTOGeometryGuard(prior.model)
    evaluator=RealTTOEvaluator(prior.model,config['supervision'])
    optimizer=JointShapePoseOptimizer(prior,config['joint'],config['loss'],config['supervision'],
        config['motion_limits'],guard,evaluator,calibration)
    measurement={}
    class BackwardMeasured(Exception):pass
    def stop_before_step(adam,*unused,**kwargs):
        torch.cuda.synchronize()
        shape=adam.param_groups[0]['params'][0];pose=adam.param_groups[1]['params'][0]
        measurement.update(peak_reserved_mib=torch.cuda.max_memory_reserved()/2**20,
            peak_allocated_mib=torch.cuda.max_memory_allocated()/2**20,
            shape_gradient_norm=float(shape.grad.norm()),translation_gradient_norm=float(pose.grad[:,:3].norm()),
            rotation_gradient_norm=float(pose.grad[:,3:].norm()),elapsed_seconds=time.monotonic()-started,
            batch_size=len(patients),patients=[p.patient_id for p in patients],
            native_cells=sum(len([r for r in observation_cells([p],config['supervision']) if r['used']]) for p in patients),
            data_manifest_sha256={p.patient_id:p.identity for p in patients},input_failures=failures,
            pretrained_sha256=prior.checkpoint_sha256,original_network_parameters_frozen=True,
            actual_operator='JointShapePoseOptimizer.optimize arm=original_motion; Adam.step intercepted before update')
        query=subprocess.run(['nvidia-smi','--query-compute-apps=pid,used_gpu_memory','--format=csv,noheader,nounits'],capture_output=True,text=True)
        measurement['context_mib']=0.
        for line in query.stdout.splitlines():
            pieces=[p.strip() for p in line.split(',')]
            if len(pieces)==2 and pieces[0]==str(os.getpid()) and pieces[1].isdigit():
                measurement['context_mib']=max(0.,float(pieces[1])-torch.cuda.memory_reserved()/2**20)
        raise BackwardMeasured()
    try:
        with patch.object(torch.optim.Adam,'step',stop_before_step):
            optimizer.optimize(patients,initial,poses,arm='original_motion')
    except BackwardMeasured:pass
    if not measurement:raise RuntimeError('No admitted Original-Motion Joint backward was reached')
    prior.assert_frozen()
    write_json(resolve(args.output),measurement)
    return 0


if __name__=='__main__':raise SystemExit(main())
